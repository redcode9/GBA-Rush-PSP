"""Write shift_table.h, the expected results of the cpu_shift_reg case.

Usage: gen_shift_table.py > shift_table.h

The values come from the ARM Architecture Reference Manual's description of
the barrel shifter for shifts by a register (data-processing operands, "by
register"): only the bottom byte of Rs counts; an amount of 0 leaves Rm and
the carry flag alone; LSL and LSR by 32 give 0 with the carry from bit 0 and
bit 31 of Rm, by more than 32 give 0 with carry 0; ASR by 32 or more fills
with bit 31, which is also the carry; ROR by a non-zero multiple of 32 leaves
Rm with the carry from bit 31, and otherwise rotates by the bottom 5 bits.
"""

MASK = 0xFFFFFFFF
KINDS = ("lsl", "lsr", "asr", "ror")

# Values of Rm: the edges of the sign and carry logic and two patterns.
RM = (0x00000000, 0x00000001, 0x80000000, 0xFFFFFFFF,
      0x7FFFFFFF, 0x87654321, 0x12345678, 0xAAAA5555)

# Values of Rs: 16 bottom bytes around 0, 32 and 255, alone and with some of
# bits 8-31 set, which must be ignored.
RS_LOW = (0, 1, 2, 7, 8, 15, 16, 30, 31, 32, 33, 34, 63, 128, 200, 255)
RS_HIGH = (0x00000100, 0xFFFFFF00, 0x80000000, 0x7FFFFF00,
           0x00010000, 0xDEADBE00, 0x00000F00, 0x01000000,
           0xFFFF0000, 0x00FF0000, 0x55555500, 0xAAAAAA00,
           0x12345600, 0x80000100, 0x0000FF00, 0xFFFFFF00)
RS = RS_LOW + tuple(low | high for low, high in zip(RS_LOW, RS_HIGH))


def shift(kind, value, rs, carry):
    """(result, carry out) of value shifted by register value rs."""
    n = rs & 0xFF
    if n == 0:
        return value, carry
    if kind == "lsl":
        if n < 32:
            return (value << n) & MASK, (value >> (32 - n)) & 1
        return 0, value & 1 if n == 32 else 0
    if kind == "lsr":
        if n < 32:
            return value >> n, (value >> (n - 1)) & 1
        return 0, value >> 31 if n == 32 else 0
    if kind == "asr":
        if n < 32:
            signed = value - (1 << 32) if value >> 31 else value
            return (signed >> n) & MASK, (value >> (n - 1)) & 1
        return (MASK if value >> 31 else 0), value >> 31
    n &= 31
    if n == 0:
        return value, value >> 31
    return ((value >> n) | (value << (32 - n))) & MASK, (value >> (n - 1)) & 1


def carry_bits(kind, value, rs):
    """Carry out with C clear in bit 0 and with C set in bit 1."""
    return shift(kind, value, rs, 0)[1] | shift(kind, value, rs, 1)[1] << 1


def words(values, per_line, fmt):
    items = [fmt % v for v in values]
    return ",\n".join("    " + ", ".join(items[i:i + per_line])
                      for i in range(0, len(items), per_line))


def table():
    out = ["/* Generated by tests/core-rom/gen_shift_table.py: do not edit. */",
           "",
           "static const u32 shift_rm[%d] =\n{\n%s\n};" %
           (len(RM), words(RM, 4, "0x%08Xu")),
           "",
           "static const u32 shift_rs[%d] =\n{\n%s\n};" %
           (len(RS), words(RS, 4, "0x%08Xu")),
           "",
           "/* [kind][rm][rs], kinds LSL, LSR, ASR, ROR. */",
           "static const u32 shift_result[4][%d][%d] =\n{" % (len(RM), len(RS))]
    for kind in KINDS:
        rows = ["  {\n%s\n  }" % words([shift(kind, m, s, 0)[0] for s in RS],
                                     4, "0x%08Xu") for m in RM]
        out.append("{\n%s\n}," % ",\n".join(rows))
    out.append("};")
    out.append("")
    out.append("/* Carry out with C clear in bit 0, with C set in bit 1. */")
    out.append("static const u8 shift_carry[4][%d][%d] =\n{" %
               (len(RM), len(RS)))
    for kind in KINDS:
        rows = ["  {\n%s\n  }" % words([carry_bits(kind, m, s) for s in RS],
                                     16, "%d") for m in RM]
        out.append("{\n%s\n}," % ",\n".join(rows))
    out.append("};")
    out.append("")
    out.append("/* The same with Rm and Rs the same register: [kind][rs]. */")
    out.append("static const u32 shift_self_result[4][%d] =\n{" % len(RS))
    for kind in KINDS:
        out.append("{\n%s\n}," % words([shift(kind, s, s, 0)[0] for s in RS],
                                       4, "0x%08Xu"))
    out.append("};")
    out.append("")
    out.append("static const u8 shift_self_carry[4][%d] =\n{" % len(RS))
    for kind in KINDS:
        out.append("{\n%s\n}," % words([carry_bits(kind, s, s) for s in RS],
                                       16, "%d"))
    out.append("};")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    print(table(), end="")
