#!/usr/bin/env python3
"""Generate the C and TLA+ views of the canonical link transition table."""

from __future__ import annotations

import argparse
import dataclasses
import difflib
import re
import sys
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "models/link/link_journal_transitions.def"
C_OUTPUT = ROOT / "source/src/link_journal_transitions.h"
TLA_OUTPUT = ROOT / "models/link/LinkJournalTransitions.tla"

STAGES = ("EMPTY", "ARMED", "DECIDED", "RELEASED")
ROLES = ("HOST", "JOINER", "EITHER")
IDENTIFIER = re.compile(r"^[a-z][a-z0-9_]*$")
TOKEN = re.compile(r"^[A-Z][A-Z0-9_]*$")


@dataclasses.dataclass(frozen=True)
class Transition:
    name: str
    source: str
    target: str
    role: str
    trigger: str
    flags: tuple[str, ...]
    guard: str


def fail(message: str) -> "NoReturn":
    raise ValueError(message)


def load_transitions() -> list[Transition]:
    transitions: list[Transition] = []
    names: set[str] = set()
    for line_number, raw_line in enumerate(
        SOURCE.read_text(encoding="utf-8").splitlines(), start=1
    ):
        line = raw_line.strip()
        if not line or line.startswith("#"):
            continue
        fields = [field.strip() for field in line.split("|")]
        if len(fields) != 7:
            fail(f"{SOURCE}:{line_number}: expected 7 fields, found {len(fields)}")
        name, source, target, role, trigger, raw_flags, guard = fields
        flags = tuple(flag.strip() for flag in raw_flags.split(",") if flag.strip())
        if not IDENTIFIER.fullmatch(name):
            fail(f"{SOURCE}:{line_number}: invalid transition name {name!r}")
        if name in names:
            fail(f"{SOURCE}:{line_number}: duplicate transition name {name!r}")
        if source not in STAGES or target not in STAGES:
            fail(f"{SOURCE}:{line_number}: invalid journal edge {source}->{target}")
        if role not in ROLES:
            fail(f"{SOURCE}:{line_number}: invalid role {role!r}")
        if not TOKEN.fullmatch(trigger):
            fail(f"{SOURCE}:{line_number}: invalid trigger {trigger!r}")
        if not flags or any(not TOKEN.fullmatch(flag) for flag in flags):
            fail(f"{SOURCE}:{line_number}: invalid transition flags {raw_flags!r}")
        if not guard or guard[-1] in ".;":
            fail(f"{SOURCE}:{line_number}: guard must be non-empty and omit punctuation")
        names.add(name)
        transitions.append(
            Transition(name, source, target, role, trigger, flags, guard)
        )
    if not transitions:
        fail(f"{SOURCE}: transition table is empty")
    validate_graph(transitions)
    return transitions


def validate_graph(transitions: list[Transition]) -> None:
    allowed_edges = {
        ("EMPTY", "ARMED"),
        ("ARMED", "EMPTY"),
        ("ARMED", "DECIDED"),
        ("DECIDED", "DECIDED"),
        ("DECIDED", "RELEASED"),
        ("RELEASED", "RELEASED"),
        ("RELEASED", "EMPTY"),
        ("EMPTY", "EMPTY"),
    }
    for transition in transitions:
        edge = (transition.source, transition.target)
        if edge not in allowed_edges:
            fail(f"{transition.name}: forbidden journal edge {edge[0]}->{edge[1]}")
        if transition.source == "DECIDED" and transition.target == "EMPTY":
            fail(f"{transition.name}: a decision cannot be cancelled")
        if transition.source == "RELEASED" and transition.target == "EMPTY":
            if "CHECKPOINT" not in transition.flags:
                fail(f"{transition.name}: clearing RELEASED must retain a checkpoint")
        if transition.source == transition.target:
            if "IDEMPOTENT" not in transition.flags:
                fail(f"{transition.name}: self-transition must be explicitly idempotent")
    required = {
        ("EMPTY", "ARMED"),
        ("ARMED", "EMPTY"),
        ("ARMED", "DECIDED"),
        ("DECIDED", "RELEASED"),
        ("RELEASED", "EMPTY"),
    }
    present = {(item.source, item.target) for item in transitions}
    missing = required - present
    if missing:
        fail(f"transition graph misses required edges: {sorted(missing)!r}")


def c_token(prefix: str, value: str) -> str:
    return f"{prefix}_{value.upper()}"


def render_c(transitions: list[Transition]) -> str:
    triggers = sorted({transition.trigger for transition in transitions})
    flags = sorted({flag for transition in transitions for flag in transition.flags})
    lines = [
        "/* Generated by tools/generate_link_transitions.py; do not edit. */",
        "#ifndef LINK_JOURNAL_TRANSITIONS_H",
        "#define LINK_JOURNAL_TRANSITIONS_H",
        "",
        "typedef enum",
        "{",
    ]
    for index, stage in enumerate(STAGES):
        comma = "," if index + 1 < len(STAGES) else ""
        lines.append(f"  {c_token('LINK_JOURNAL', stage)}{comma}")
    lines.extend(["} LinkJournalStage;", "", "typedef enum", "{"])
    for index, role in enumerate(ROLES):
        comma = "," if index + 1 < len(ROLES) else ""
        lines.append(f"  {c_token('LINK_JOURNAL_ROLE', role)}{comma}")
    lines.extend(["} LinkJournalRole;", "", "typedef enum", "{"])
    for index, transition in enumerate(transitions):
        lines.append(
            f"  {c_token('LINK_JOURNAL_TRANSITION', transition.name)},"
        )
    lines.append("  LINK_JOURNAL_TRANSITION_ID_COUNT")
    lines.extend(["} LinkJournalTransitionId;", "", "typedef enum", "{"])
    for index, trigger in enumerate(triggers):
        comma = "," if index + 1 < len(triggers) else ""
        lines.append(f"  {c_token('LINK_JOURNAL_TRIGGER', trigger)}{comma}")
    lines.extend(["} LinkJournalTrigger;", "", "typedef enum", "{"])
    for index, flag in enumerate(flags):
        comma = "," if index + 1 < len(flags) else ""
        lines.append(f"  {c_token('LINK_JOURNAL_FLAG', flag)} = 1u << {index}{comma}")
    lines.extend(["} LinkJournalTransitionFlag;", "", "typedef struct", "{"])
    lines.extend(
        [
            "  const char *name;",
            "  LinkJournalStage source;",
            "  LinkJournalStage target;",
            "  LinkJournalRole role;",
            "  LinkJournalTrigger trigger;",
            "  unsigned int flags;",
            "} LinkJournalTransition;",
            "",
            "#define LINK_JOURNAL_TRANSITION_ROWS(X) \\",
        ]
    )
    for index, transition in enumerate(transitions):
        flag_expr = " | ".join(
            c_token("LINK_JOURNAL_FLAG", flag) for flag in transition.flags
        )
        suffix = " \\" if index + 1 < len(transitions) else ""
        lines.append(
            "  X(\"{}\", {}, {}, {}, {}, {}){}".format(
                transition.name,
                c_token("LINK_JOURNAL", transition.source),
                c_token("LINK_JOURNAL", transition.target),
                c_token("LINK_JOURNAL_ROLE", transition.role),
                c_token("LINK_JOURNAL_TRIGGER", transition.trigger),
                flag_expr,
                suffix,
            )
        )
    lines.extend(
        [
            "",
            "#define LINK_JOURNAL_COUNT_ROW(name, source, target, role, trigger, flags) + 1",
            "enum { LINK_JOURNAL_TRANSITION_COUNT = 0 LINK_JOURNAL_TRANSITION_ROWS(LINK_JOURNAL_COUNT_ROW) };",
            "#undef LINK_JOURNAL_COUNT_ROW",
            "",
            "#endif /* LINK_JOURNAL_TRANSITIONS_H */",
            "",
        ]
    )
    return "\n".join(lines)


def render_tla(transitions: list[Transition]) -> str:
    def record(transition: Transition) -> str:
        flags = ", ".join(f'"{flag}"' for flag in transition.flags)
        return (
            "  [name |-> \"{}\", from |-> \"{}\", to |-> \"{}\", "
            "role |-> \"{}\", trigger |-> \"{}\", flags |-> {{{}}}]".format(
                transition.name,
                transition.source,
                transition.target,
                transition.role,
                transition.trigger,
                flags,
            )
        )

    records = ",\n".join(record(transition) for transition in transitions)
    return "\n".join(
        [
            "---- MODULE LinkJournalTransitions ----",
            "\\* Generated by tools/generate_link_transitions.py; do not edit.",
            "",
            f"JournalStages == {{{', '.join(chr(34) + s + chr(34) for s in STAGES)}}}",
            f"JournalRoles == {{{', '.join(chr(34) + r + chr(34) for r in ROLES)}}}",
            "",
            "JournalTransitionTable == {",
            records,
            "}",
            "",
            "IsLegalJournalTransition(name, role, source, target) ==",
            "  \\E transition \\in JournalTransitionTable:",
            "    /\\ transition.name = name",
            "    /\\ transition.from = source",
            "    /\\ transition.to = target",
            "    /\\ transition.role \\in {role, \"EITHER\"}",
            "",
            "=======================================",
            "",
        ]
    )


def check_or_write(path: Path, content: str, check: bool) -> bool:
    old = path.read_text(encoding="utf-8") if path.exists() else ""
    if old == content:
        return True
    if not check:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        return True
    diff = difflib.unified_diff(
        old.splitlines(),
        content.splitlines(),
        fromfile=str(path),
        tofile=f"generated:{path}",
        lineterm="",
    )
    print("\n".join(diff), file=sys.stderr)
    return False


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--check", action="store_true", help="fail if generated files are stale"
    )
    args = parser.parse_args()
    try:
        transitions = load_transitions()
        current = check_or_write(C_OUTPUT, render_c(transitions), args.check)
        current &= check_or_write(TLA_OUTPUT, render_tla(transitions), args.check)
    except (OSError, ValueError) as error:
        print(error, file=sys.stderr)
        return 1
    if not current:
        print("generated link transition files are stale", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
